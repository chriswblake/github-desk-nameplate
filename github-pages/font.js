  var FONTS = { narrow: narrow, regular: regular, wide: wide };

  function fontFor(size) {
    return FONTS[size] || FONTS.regular;
  }

  // Validate at load: every glyph is 7 rows of equal length within the size cap.
  function validate() {
    var bad = [];
    Object.keys(FONTS).forEach(function (size) {
      var cap = SIZES[size];
      var font = FONTS[size];
      for (var ch in font) {
        if (!Object.prototype.hasOwnProperty.call(font, ch)) continue;
        var g = font[ch];
        if (!Array.isArray(g) || g.length !== ROWS) {
          bad.push(size + " '" + ch + "': not 7 rows");
          continue;
        }
        var w = g[0].length;
        if (w > cap && ch !== " ") bad.push(size + " '" + ch + "': width " + w + " > " + cap);
        for (var r = 0; r < ROWS; r++) {
          if (g[r].length !== w) {
            bad.push(size + " '" + ch + "': row " + r + " width mismatch");
            break;
          }
        }
      }
    });
    if (bad.length && global.console) console.warn("[font] malformed glyphs:", bad);
    return bad;
  }

  function glyphWidth(ch, size) {
    var g = fontFor(size)[ch];
    return g ? g[0].length : 0;
  }

  function charColumns(ch, size) {
    var g = fontFor(size)[ch];
    if (!g) return [];
    var cols = [];
    var w = g[0].length;
    for (var c = 0; c < w; c++) {
      var col = [];
      for (var r = 0; r < ROWS; r++) col.push(g[r].charAt(c) === "#");
      cols.push(col);
    }
    return cols;
  }

  validate();

  global.NameplateFont = {
    FONTS: FONTS,
    SIZES: SIZES,
    ROWS: ROWS,
    glyphWidth: glyphWidth,
    charColumns: charColumns,
    validate: validate
  };
